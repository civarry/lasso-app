import CoreGraphics
import Foundation
import Observation

/// One conversation. The Chat panel holds several of these (`ChatController.sessions`) and shows one
/// at a time (`active`) — so opening "Continue in chat" or an Ask-AI thread spawns a *new* session
/// instead of wiping the one you were working in.
///
/// This is a self-contained state container: its own message history, two-track summary memory,
/// semantic index, pending attachments, and in-flight task handles. `ChatController` owns the logic
/// and drives whichever session is `active`; background tasks capture their session so they always
/// update the right conversation even after the user switches away.
@MainActor
@Observable
final class Conversation: Identifiable {
    let id = UUID()
    let createdAt = Date()

    /// What kind of conversation this is — where it began. Drives the recents-menu icon and the
    /// fallback title. (Origin is metadata, not a subclass — every conversation is uniform.)
    enum Kind: Sendable {
        case general, selection, image, askAI
        var systemImage: String {
            switch self {
            case .general: "bubble.left.and.text.bubble.right"
            case .selection: "text.viewfinder"
            case .image: "photo"
            case .askAI: "sparkles"
            }
        }
        var label: String {
            switch self {
            case .general: "New conversation"
            case .selection: "Selection"
            case .image: "Image"
            case .askAI: "Ask AI"
            }
        }
    }

    /// What this conversation is *about* — the source it was seeded from. Stored for better titles and
    /// future "open the source" actions (the natural bridge to a Workspace later).
    enum Anchor { case image(CGImage); case selection(String) }

    var kind: Kind = .general
    var anchor: Anchor?
    /// A short name generated by the background summary pass once the chat is substantial — so a long
    /// conversation reads as "Trip Planning" instead of its first message. Falls back gracefully.
    var autoTitle: String?

    // MARK: Conversation state
    var messages: [ChatMessage] = []
    var input = ""
    var pendingAttachments: [Attachment] = []
    var seededContext: String?
    var isStreaming = false
    var trimmedNotice = false
    var streamTask: Task<Void, Never>?

    // MARK: Memory (two-track summary + in-session semantic retrieval) — per session
    var memory = ConversationMemory()
    var summarizedTurnCount = 0
    var summaryTask: Task<Void, Never>?
    let memoryIndex = ChatMemoryIndex()
    var indexTask: Task<Void, Never>?

    /// Header/recents-menu label: the generated title if any, else the first user message, else the
    /// selection text it's anchored to, else the kind's label.
    var title: String {
        if let autoTitle, !autoTitle.isEmpty { return autoTitle }
        if let first = messages.first(where: { $0.role == .user })?
            .text.trimmingCharacters(in: .whitespacesAndNewlines), !first.isEmpty {
            return String(first.prefix(42))
        }
        if case .selection(let text)? = anchor {
            let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
            if !t.isEmpty { return String(t.prefix(42)) }
        }
        return kind.label
    }

    /// Recents-menu icon for this conversation's kind.
    var systemImage: String { kind.systemImage }

    var hasMessages: Bool { !messages.isEmpty }
    /// Whether there's anything to clear (drives New chat / can-clear affordances).
    var canClear: Bool {
        !messages.isEmpty || !input.isEmpty || !pendingAttachments.isEmpty || seededContext != nil
    }

    /// Cancel any in-flight work — called before a session is dropped or switched away from.
    func cancelWork() {
        streamTask?.cancel(); streamTask = nil
        summaryTask?.cancel(); summaryTask = nil
        indexTask?.cancel(); indexTask = nil
    }
}
